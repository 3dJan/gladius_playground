#include "TranslucencyCodeGenerator.h"

#include "Assembly.h"
#include "ModelUtils.h"
#include "ToOCLVisitor.h"

#include <sstream>

namespace gladius::nodes
{
    namespace
    {
        /// @brief Entry point used when the model is opaque, so the kernels never need a
        /// compile-time switch between a present and a missing translucency function.
        constexpr char STUB_SOURCE[] =
          "float translucencyModel(float3 pos, PAYLOAD_ARGS)\n{\n    return 0.f;\n}\n";
    }

    std::string createOpaqueTranslucencyKernelSource()
    {
        return STUB_SOURCE;
    }

    TranslucencyKernelSource createTranslucencyKernelSource(Assembly & assembly)
    {
        auto const assemblyModel = assembly.assemblyModel();
        if (!assemblyModel || !isQualifiedForTranslucency(*assemblyModel))
        {
            return {.source = STUB_SOURCE, .active = false};
        }

        // The translucency entry point is generated by inlining the whole graph, so it can only be
        // emitted for an assembly whose sub-models have already been flattened away.
        if (assembly.getFunctions().size() > 1u)
        {
            return {.source = STUB_SOURCE, .active = false};
        }

        try
        {
            ToOclVisitor visitor;
            visitor.setEvaluatorChannel(EvaluatorChannel::Translucency);
            assembly.visitAssemblyNodes(visitor);

            std::stringstream translucencyKernel;
            visitor.write(translucencyKernel);
            auto source = translucencyKernel.str();
            if (source.empty())
            {
                return {.source = STUB_SOURCE, .active = false};
            }
            return {.source = std::move(source), .active = true};
        }
        catch (std::exception const &)
        {
            // A graph the OpenCL backend cannot express stays opaque instead of failing the render
            // program. The shape/color source was already generated successfully at this point.
            return {.source = STUB_SOURCE, .active = false};
        }
    }
} // namespace gladius::nodes
